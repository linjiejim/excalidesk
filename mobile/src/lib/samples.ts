function makeSample(id: string, name: string, sceneObj: unknown, offsetHours: number): DrawingFileItem {
  const rawJson = JSON.stringify(sceneObj);
  const summary = summarizeScene(parseExcalidrawJson(rawJson));
  return {
    id,
    name,
    folderName: "Sample",
    relativePath: `${name}.excalidraw`,
    source: "sample",
    mtime: Date.now() - offsetHours * 3600 * 1000,
    size: rawJson.length,
    isUbiquitous: false,
    downloaded: true,
    elementCount: summary.liveCount,
    slideCount: summary.slideCount,
    searchText: summary.searchText,
    rawJson,
  };
}

